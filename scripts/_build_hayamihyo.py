def mark(text):
    """「確認中」を太字＋下線で目立たせる（白黒印刷でも読める）。"""
    s = e(text)
    return s.replace("確認中", '<span class="pend">確認中</span>')


def main():
    cities = []
    for fn in ("sodai_core9.json", "sodai_other21.json"):
        with open(os.path.join(DATA, fn), encoding="utf-8") as f:
            cities += json.load(f)
    problems = []
    ids = [c["cityId"] for c in cities]
    if len(ids) != 30:
        problems.append(f"市町村数が30ではない: {len(ids)}")
    for i in ids:
        if i not in SUMMARY:
            problems.append(f"SUMMARY に無い: {i}")
    rows = []
    for c in cities:
        s = SUMMARY.get(c["cityId"])
        if not s:
            continue
        for key, txt in zip(("apply_method", "fee_system", "bring_in"), s):
            if "[要確認]" in (c.get(key) or "") and "確認中" not in txt:
                problems.append(f"{c['cityId']}: {key} に[要確認]があるが要約に「確認中」が無い")
        url = c["sodai_official_url"]
        rows.append(
            "<tr>"
            f'<td class="c">{e(c["city"])}<small>確認 {e(c["checked_date"])}</small></td>'
            f"<td>{mark(s[0])}</td><td>{mark(s[1])}</td><td>{mark(s[2])}</td>"
            f'<td class="u"><a href="{e(url)}">{e(url)}</a></td>'
            "</tr>"
        )
    if problems:
        print("\n".join(problems), file=sys.stderr)
        sys.exit(1)
